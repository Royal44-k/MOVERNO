import {spawnSync} from 'node:child_process';
import {mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const id=process.argv[2];
assert.ok(['A01','A02','A03'].includes(id));
mkdirSync('../renders/final',{recursive:true});
const source=resolve(`../renders/MOVERNO-${id}-30s-v2.mp4`);
const target=resolve(`../renders/final/MOVERNO-${id}-30s.mp4`);
const ffmpeg=resolve('node_modules/ffmpeg-static/ffmpeg.exe');
const probe=resolve('../remotion/node_modules/@remotion/compositor-win32-x64-msvc/ffprobe.exe');
const encode=spawnSync(ffmpeg,['-v','error','-n','-i',source,'-map','0:v:0','-map','0:a:0','-c:v','copy','-c:a','aac','-b:a','192k','-t','30','-movflags','+faststart',target],{encoding:'utf8',windowsHide:true});
assert.equal(encode.status,0,encode.stderr);
const meta=spawnSync(probe,['-v','error','-show_entries','stream=codec_name,width,height,r_frame_rate,nb_frames,duration','-show_entries','format=duration,size','-of','json',target],{encoding:'utf8',windowsHide:true});
assert.equal(meta.status,0,meta.stderr);
const info=JSON.parse(meta.stdout), video=info.streams.find(s=>s.codec_name==='h264'), audio=info.streams.find(s=>s.codec_name==='aac');
assert.ok(video && audio,'Both video and audio must be present');
assert.equal(Number(video.nb_frames),900);
assert.equal(video.width,1080);assert.equal(video.height,1920);assert.equal(video.r_frame_rate,'30/1');
assert.equal(Number(info.format.duration),30);
assert.equal(Number(video.duration),30);assert.equal(Number(audio.duration),30);
console.log(JSON.stringify({id,path:target,verified:info},null,2));
